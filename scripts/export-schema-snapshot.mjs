#!/usr/bin/env node
// Generates skillstrader-frontend/src/lib/pocketbase/schema-snapshot.ts, the field-name snapshot
// that schema-snapshot.test.ts compares the candidate write payload against.
//
// Why this exists: docs/system-improvements.md S5 is the bug class where the frontend keeps sending
// a field that a migration already dropped. PocketBase discards unknown body fields silently, so the
// input looks accepted and then reads back empty -- `school_other_name` did exactly that. Comparing
// the payload against the schema the migrations actually produce turns that into a failing test.
//
// It replays pb_migrations/ into a throwaway directory and never opens the live pb_data/, so it needs
// no superuser and is safe to run any time.
//
//   node scripts/export-schema-snapshot.mjs            # write the snapshot
//   node scripts/export-schema-snapshot.mjs --verify   # fail if the committed snapshot is stale
//
// --verify is the pre-deploy gate: CI has no PocketBase binary (see scripts/check-api-rules.mjs), so
// freshness is asserted here rather than in the browser test, which cannot read the filesystem.
import { DatabaseSync } from 'node:sqlite';
import { execFileSync } from 'node:child_process';
import { rmSync, existsSync, writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const throwaway = path.join(repoRoot, '.qwen', 'tmp', 'pbschema');
const outDir = path.join(repoRoot, 'skillstrader-frontend', 'src', 'lib', 'pocketbase');
const outPath = path.join(outDir, 'schema-snapshot.ts');

const BINARY =
  process.env.POCKETBASE_BIN ||
  path.join(repoRoot, process.platform === 'win32' ? 'pocketbase.exe' : 'pocketbase');

if (!existsSync(BINARY)) {
  console.error(`PocketBase binary not found at ${BINARY}\nSet POCKETBASE_BIN to a pocketbase executable.`);
  process.exit(2);
}

const migrations = execFileSync('git', ['ls-files', 'pb_migrations'], { cwd: repoRoot, encoding: 'utf8' })
  .split(/\r?\n/)
  .filter((f) => f.endsWith('.js'))
  .map((f) => path.basename(f))
  .sort();

rmSync(throwaway, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
execFileSync(BINARY, ['migrate', 'up', '--dir', throwaway, '--migrationsDir', 'pb_migrations'], {
  cwd: repoRoot,
  stdio: ['ignore', 'ignore', 'inherit'],
});

const db = new DatabaseSync(path.join(throwaway, 'data.db'), { readOnly: true });
const rows = db.prepare('select name, fields from _collections order by name').all();
db.close();
rmSync(throwaway, { recursive: true, force: true });

const collections = {};
const selects = {};
for (const row of rows) {
  const fields = JSON.parse(row.fields);
  collections[row.name] = fields.map((field) => field.name).sort();
  // A select field only accepts its declared values, and PocketBase rejects a create or update
  // that sends anything else. Recording them here is what lets a test catch a frontend enum that
  // disagrees with the schema -- job_orders.status was stored lowercase while JobOrders.tsx wrote
  // "Open", which silently broke the badge, the filter and the save path at once.
  const byName = {};
  for (const field of fields) {
    if (/select/i.test(field.type ?? '') && Array.isArray(field.values)) {
      byName[field.name] = [...field.values].sort();
    }
  }
  if (Object.keys(byName).length > 0) selects[row.name] = byName;
}

// generatedFrom.lastMigration is the chain tip. The freshness is checked by --verify, because a
// browser test cannot read the filesystem to notice a new migration landed unregenerated.
const snapshot = {
  generatedFrom: {
    lastMigration: migrations[migrations.length - 1],
    migrationCount: migrations.length,
  },
  collections,
  selects,
};

const body = `// GENERATED by scripts/export-schema-snapshot.mjs -- do not edit by hand.
//
// Field names per PocketBase collection, produced by replaying pb_migrations/ into a throwaway
// directory. schema-snapshot.test.ts uses it to prove the candidate write payload only sends real
// columns; regenerate with:
//
//   node scripts/export-schema-snapshot.mjs
//
// and verify freshness before deploying with:
//
//   node scripts/export-schema-snapshot.mjs --verify
export const schemaSnapshot = ${JSON.stringify(snapshot, null, 2)} as const;

export type SchemaSnapshot = typeof schemaSnapshot;
`;

if (process.argv.includes('--verify')) {
  if (!existsSync(outPath)) {
    console.error(`RESULT: FAIL -- ${path.relative(repoRoot, outPath)} does not exist. Run the export first.`);
    process.exit(1);
  }
  const committed = readFileSync(outPath, 'utf8');
  if (committed === body) {
    console.log(`RESULT: PASS -- snapshot matches the migration chain (tip ${snapshot.generatedFrom.lastMigration})`);
    process.exit(0);
  }
  console.error(
    `RESULT: FAIL -- the committed schema snapshot is stale.\n` +
      `  chain tip: ${snapshot.generatedFrom.lastMigration} (${snapshot.generatedFrom.migrationCount} migrations)\n` +
      '  Run: node scripts/export-schema-snapshot.mjs\n' +
      '  Then re-read the diff: a dropped column means the frontend may still be writing it.',
  );
  process.exit(1);
}

writeFileSync(outPath, body);
console.log(
  `wrote ${path.relative(repoRoot, outPath)}\n  ${Object.keys(collections).length} collections, chain tip ${snapshot.generatedFrom.lastMigration}`,
);
